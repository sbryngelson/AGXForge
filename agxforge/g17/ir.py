# WHICH ATOMIC DECLARATIONS AN ATOMIC OPERATION MAY REACH, named per spelling because _DECL_ONLY
# cannot imply it - `atomic_uint` and `atomic_float` are both (4 bytes, 1 lane) and only one of
# them has a measured operation. The per-lane device form op10090 is measured on 32-bit INTEGER
# operands (add and `and`, read off Apple's own compilations); no float atomic has been measured
# here at all, so `atomic_float` stays declaration-only and an atomic on one refuses by name
# rather than borrowing the integer form's measurement.
# SIGNEDNESS IS CARRIED HERE EVEN THOUGH THE STORAGE IS THE SAME, because the source metadata
# states it: `air.struct_type_info` names the field `"int"` or `"uint"`, and two of these sources
# differ on exactly that while both have `type { i32 }` storage. Root caught the collapse. The
# operation reaches the same 32-bit element either way - `and` does not read signedness - so both
# map to I32 here; what the separate spellings preserve is the DECLARATION, which is the thing a
# contract is for.
ATOMIC_ELEMS = {"atomic_uint": I32, "atomic_int": I32}

# THE WORD COMPONENTS OF A WIDE SCALAR, WHICH IS NOT A VECTOR DECOMPOSITION.
#
# `ulong` is ONE eight-byte element. Calling its halves "lanes" would claim a scalar is a vector -
# false in the ABI and explicitly forbidden by the assignment - so this is a separate map with a
# separate name, and the declaration stays `ulong` with its 8-byte size and 8-byte alignment. What
# it says is narrower: such an element may be ACCESSED as two consecutive 32-bit words.
#
# THE ORDER IS LOW WORD FIRST and it is part of the contract, not an implementation detail: the
# component at word index 2i is the low half of element i and 2i+1 is the high half. Every
# composition below depends on that, and `component=` names it at every call site rather than
# leaving a bare 0/1 to be read as an offset.
WORD_COMPONENTS = {"long": I32, "ulong": I32}
WORD_COMPONENT_COUNT = 2
WORD_COMPONENT_ACCESS_KINDS = frozenset({"load", "store_at"})


def _is_word_component_access(op, buf):
    """A word-component access is a word-width load or store CARRYING an explicit component.

    The `component` attribute is what distinguishes this from an ordinary word access that merely
    happens to name a wide buffer: an access without it is ambiguous about which half it means, and
    ambiguous is what this must refuse rather than default.
    """
    if op.kind not in WORD_COMPONENT_ACCESS_KINDS:
        return False
    if op.attrs.get("component") is None:
        return False
    if op.attrs.get("width", "word") != "word":
        return False
    return bool(op.args) and op.args[0] is buf
DECL_ELEM = {}          # spelling -> the element key, which is the spelling itself
# THE LANE TYPE OF A VECTOR DECLARATION, stated explicitly because the table above cannot imply it.
#
# _DECL_ONLY records lane_bytes and signedness, and those two do NOT determine the lane's element:
# `bfloat2` and `half2` are both (2 bytes, float) and only one of them has an accessible lane. So
# the lane element is named here per spelling, and a spelling absent from this map has no lane
# decomposition this backend will access - which keeps `ulong`, `long`, `uchar` and BOTH bfloat
# vectors refusing exactly as before.
#
# WHAT THIS ADMITS is one thing only: a load or a store whose width is the lane's width, on a
# buffer whose declaration stays the vector spelling. The declared element still reaches the ABI
# unchanged (cc.py reads ELEM_NAMES/ELEM_BYTES of buf.elem), and the emitted address already
# strides by the ACCESS width rather than by the declaration, so a lane access needs no new
# address arithmetic and no new form. Anything else that names such a buffer - a whole-element
# access, an atomic, an address escape - still refuses with the message below.
LANE_ELEM = {"uint2": I32, "uint4": I32, "int4": I32,
             "float2": F32, "float4": F32,
             "half2": F16, "half4": F16, "short2": I16}
LANE_ACCESS_KINDS = ("load", "store", "store_at", "store_range")


def lane_width_name(lane):
    """"half" or "word" for a lane element - the access width a lane load/store must carry."""
    return "half" if ELEM_BYTES[lane] == 2 else "word"


# WHICH DECLARATION ADMITS A BFLOAT TRANSPORT READ, and why it is a READ only.
#
# `bfloat` is two bytes with two-byte alignment and this backend loads two-byte scalars, so the
# LOAD needs no new form: it is the measured halfword load, the same op12646 element-width form
# `half` and `i16` already take. What makes bfloat different from `half` is not the access, it is
# the FORMAT - bfloat16 is the top sixteen bits of binary32, so widening is a shift rather than a
# conversion instruction, and that composition lives in the front end.
#
# SO THE ELEMENT STAYS OUT OF ACCESSIBLE_ELEMS and this admits exactly one shape. A bfloat STORE is
# NOT admitted: narrowing binary32 to bfloat needs a rounding contract whose signed-zero and
# overflow-to-infinity domains are unadjudicated (see the feasibility handoff), and admitting the
# store would let that unadjudicated rounding into emitted code. Nor is a vector lane, nor an
# address escape, nor an atomic. Marking bfloat writable to admit the read would have been the
# cheap version of this and it is the wrong one: the read and the write rest on different evidence.
BFLOAT_TRANSPORT = frozenset({"bfloat"})
BFLOAT_TRANSPORT_ACCESS_KINDS = frozenset({"load"})


def _is_bfloat_transport_read(op, buf):
    """A bfloat transport read is an element-width LOAD and nothing else."""
    if op.kind not in BFLOAT_TRANSPORT_ACCESS_KINDS:
        return False
    if op.attrs.get("width", "word") != "half":
        return False
    if op.attrs.get("component") is not None:
        return False
    return True


def _is_lane_access(op, lane):
    """A lane access is a load or store of exactly the lane's width. Nothing else qualifies."""
    if op.kind not in LANE_ACCESS_KINDS:
        return False
    return op.attrs.get("width", "word") == lane_width_name(lane)


# The per-lane accesses an atomic declaration admits: the fetch-family read-modify-write or
# compare-exchange, whose address is the buffer itself. Deliberately not the uniform
# form: op10094 is a different opcode wrapped in a lane election, and substituting it for a
# per-lane address would change what the program does.
ATOMIC_ACCESS_KINDS = frozenset({"atomic_add", "atomic_cmpxchg"})


def _is_atomic_access(op, buf):
    """True for a per-lane atomic RMW whose ADDRESS is this buffer.

    The buffer has to be the address operand rather than merely present: an atomic whose VALUE
    came from an atomic-declared buffer would be an ordinary read of it, which is the access this
    declaration does not admit.
    """
    if op.kind not in ATOMIC_ACCESS_KINDS:
        return False
    return bool(op.args) and op.args[0] is buf


DECL_PHYSICAL = {}      # element key -> dict(bytes, alignment, lanes, lane_bytes, signedness)
for _n, _b, _a, _l, _lb, _sg, _w in _DECL_ONLY:
    DECL_ELEM[_n] = _n
    DECL_PHYSICAL[_n] = dict(bytes=_b, alignment=_a, lanes=_l, lane_bytes=_lb, signedness=_sg,
                             air_metadata_declarations=_w)
    ELEM_BYTES[_n] = _b
    ELEM_NAMES[_n] = _n
# and the four accessible ones get a physical description too, so every binding has one
# The four accessible elements get a physical description too, so every binding has one. Their
# signedness is the one the ABI has always stated, which is NOT always the one the source declared:
# a signed `int` or `short` buffer has been carried as `uint`/`ushort` since this ABI existed, and
# this batch does not change that - see the handoff. It is stated here rather than quietly implied.
for _e, _sg, _w in ((I16, "unsigned", 49), (F16, "float", 95), (I32, "unsigned", 288),
                    (F32, "float", 129)):
    DECL_PHYSICAL[_e] = dict(bytes=ELEM_BYTES[_e], alignment=ELEM_BYTES[_e], lanes=1,
                             lane_bytes=ELEM_BYTES[_e], signedness=_sg,
                             air_metadata_declarations=_w)



# THE SOURCE'S OWN SPELLING, CARRIED BESIDE THE LOWERING TYPE. `Buffer.elem` is the type this
# backend lowers to, and it is deliberately NOT always the spelling the source wrote: a signed
# `int` buffer has been carried as `uint` and a `short` as `ushort` since this ABI existed, which
# the DECL_PHYSICAL comment above already states. That choice stays exactly as it is.
#
# What was missing is the source fact itself. Root found it while defining the public projection
# record: for all four resource-model targets the decoded declaration metadata differs from the IR
# spelling at index 1 (`int`) and index 6 (`short`), widths agreeing everywhere, and a projected
# program needs the ORIGINAL declarations rather than the lowered ones. So `declared_element`
# retains the spelling, and nothing reads it for selection, admission or the default ABI.
#
# THE TWO ALIASES ARE THE MEASURED ONES AND NOT A LICENCE. `g17front`'s own `elem_of` admits
# exactly `int -> I32` and `short -> I16` on top of the canonical inverse of ELEM_NAMES; this
# mirrors that set deliberately rather than allowing any same-width substitution. A `float`
# declaration over an `i32` element is the same four bytes and a different type, and it refuses.
DECLARED_ALIASES = {I32: ("int",), I16: ("short",)}


def declared_spellings():
    """Every spelling a declaration may state: the canonical names plus the two signed aliases."""
    return set(ELEM_NAMES.values()) | {a for aliases in DECLARED_ALIASES.values() for a in aliases}


def check_declared_element(elem, declared):
    """Validate a source spelling against the element it lowers to; return the spelling.

    `None` means "authored IR with no separate source spelling", which takes the canonical name.
    """
    canonical = ELEM_NAMES[elem]
    if declared is None:
        return canonical
    if not isinstance(declared, str):
        raise IRError("declared element %r is not a spelling" % (declared,))
    if declared == canonical:
        return declared
    if declared in DECLARED_ALIASES.get(elem, ()):
        return declared
    if declared not in declared_spellings():
        raise IRError("unknown declared element spelling %r; the spellings this IR carries are %s"
                      % (declared, ", ".join(sorted(declared_spellings()))))
    same_width = ELEM_BYTES.get(elem) == ELEM_BYTES.get(
        {v: k for k, v in ELEM_NAMES.items()}.get(declared, declared))
    raise IRError(
        "declared element %r is not compatible with lowering element %r (canonical %r)%s: the only "
        "aliases this IR admits are %s, so a different type is refused rather than carried"
        % (declared, elem, canonical,
           "; both are the same width, which is not sufficient" if same_width else "",
           ", ".join("%s for %s" % (a, e) for e, al in sorted(DECLARED_ALIASES.items())
                     for a in al)))


def elem_alignment(elem):
    """The declared alignment of one element, for the ABI to state."""
    return DECL_PHYSICAL[elem]["alignment"]

_ids = itertools.count()

class Value:
    """One SSA value. Produced by exactly one Op, consumed by any number."""
    __slots__ = ("id", "type", "name", "op")
    def __init__(self, type=I32, name=None, op=None):
        self.id = next(_ids); self.type = type; self.op = op
        self.name = name or "v%d" % self.id
    def __repr__(self): return "%%%s" % self.name

class Imm:
    """An immediate operand. Distinct from Value so selection can pick the operand MODE."""
    __slots__ = ("v",)
    def __init__(self, v): self.v = int(v)
    def __repr__(self): return str(self.v)
    def __eq__(self, o): return isinstance(o, Imm) and o.v == self.v
    def __hash__(self): return hash(("Imm", self.v))

class Buffer:
    """A device pointer argument, referred to by name and bound to a slot by the launch.

    `elem` is the type this backend lowers to. `declared_element` is the spelling the SOURCE used,
    which for a signed `int` or `short` buffer is not the same string - see check_declared_element.
    Authored IR that states no spelling gets the canonical one, so the field is always populated.
    """
    __slots__ = ("name", "slot", "elem", "declared_element")
    def __init__(self, name, slot, elem=I32, declared_element=None):
        if elem not in ELEM_BYTES:
            raise IRError("buffer element type %r; the recovered ones are %s"
                          % (elem, ", ".join(sorted(ELEM_BYTES))))
        self.name = name; self.slot = slot; self.elem = elem
        self.declared_element = check_declared_element(elem, declared_element)
    def __repr__(self): return "@%s" % self.name

