# --- verifier -----------------------------------------------------------------------------
class IRError(Exception): pass

# The deepest nesting observed in Apple's own output (ledger/g17-predication-nests.toml). Not a
# hardware limit - a limit on what has been measured.
MAX_PRED_DEPTH = 4


# WHICH OPERANDS MAY BE A CONSTANT. Every op below takes its non-listed operands in REGISTERS, and
# an Imm in one of those positions is a language error rather than a missing lowering: the backend
# hands its `uses` list straight to the allocator, which then reports `use before def of 0` from a
# place that names neither the op nor the operand. Widening the program set found it - a
# threadgroup round trip written as store_tg(v, Imm(0)) - and nothing in nineteen rungs had ever
# put a constant where a register goes. The buffer-index positions stay open because an index is
# meaningful either way and the backend answers with Unsupported, which is the honest distinction:
# `store` to a computed index is a lowering the ISA does not have, `store_tg` to a constant index
# is a sentence the IR cannot say.
IMM_OPERANDS = {"const": {0}, "cmp": {1},
                "load": {1}, "store": {1}, "store_at": {1}, "store_range": {1}, "store_fetch": {1}, "uniform_load": {1}, "vec_lane": {1}}
for _k in ARITH - {"shiftadd"}:
    # operand B alone: every ALU form places its immediate in the second slot, and a constant
    # first operand is a different opcode the backend refuses by name.
    IMM_OPERANDS[_k] = {1}

def verify(fn):
    """Reject in the IR what the backend cannot lower, so failures are legible here rather than
    as wrong bytes later."""
    # Predication must be balanced and must NOT nest: the mask's depth behaviour is unmeasured,
    # so a nested region is refused rather than assumed to stack.
    for blk in fn.blocks:
        depth = 0
        for op in blk.ops:
            if op.kind == "exec_mask":
                depth += 1
                if depth > MAX_PRED_DEPTH:
                    raise IRError("predication nested %d deep in block %r; %d is the deepest "
                                  "Apple's compiler was observed to emit and the mask stack has "
                                  "not been measured beyond it" % (depth, blk.label, MAX_PRED_DEPTH))
            elif op.kind == "exec_restore":
                depth -= 1
                if depth < 0:
                    raise IRError("exec_restore without a matching exec_mask in %r" % blk.label)
        if depth: raise IRError("block %r ends with %d unrestored exec_mask" % (blk.label, depth))
    labels = {b.label: b for b in fn.blocks}
    if len(labels) != len(fn.blocks): raise IRError("duplicate block label")
    defined = set()
    for b in fn.blocks:
        if not b.ops: raise IRError("block %s is empty" % b.label)
        for i, o in enumerate(b.ops):
            last = i == len(b.ops) - 1
            if (o.kind in TERMS) != last:
                raise IRError("block %s: terminator must be last and present (%r)" % (b.label, o))
            # `machine` is the one kind that may or may not define a value: an instruction whose
            # destination is a FLAGR writes to a register file the allocator does not manage, so it
            # is authored as a fixed operand and the instruction defines nothing an IR value can
            # hold. Every other kind still has to match its class exactly.
            if o.kind != "machine" and (o.dest is not None) != (o.kind in DEFS):
                raise IRError("block %s: %r defines a value iff its kind does" % (b.label, o))
            for ai, a in enumerate(o.args):
                # A PHI IS THE ONE OP THAT MAY USE A VALUE DEFINED LATER. Its latch argument is
                # produced by the loop body, which is by definition below the header; requiring
                # dominance here would make a loop-carried value unexpressible.
                if isinstance(a, Value) and a not in defined and o.kind != "phi":
                    raise IRError("block %s: %r uses %r before it is defined" % (b.label, o, a))
                if isinstance(a, Block) and a.label not in labels:
                    raise IRError("block %s: %r targets an unknown block" % (b.label, o))
                if isinstance(a, Buffer) and a not in fn.buffers:
                    raise IRError("block %s: %r uses unbound buffer %r" % (b.label, o, a))
                if isinstance(a, Imm) and ai not in IMM_OPERANDS.get(o.kind, ()):
                    raise IRError("block %s: %r takes operand %d in a register, not as the "
                                  "constant %r - materialise it with const() first"
                                  % (b.label, o, ai, a))
            if o.dest is not None: defined.add(o.dest)
    # PHI PLACEMENT. A phi must head its block, because it is a coalescing constraint on the
    # register live across the back edge and anything emitted before it would be inside the loop
    # body on the second pass but not on the first.
    targets = {a for b in fn.blocks for o in b.ops for a in o.args if isinstance(a, Block)}
    for b in fn.blocks:
        seen_other = False
        for o in b.ops:
            if o.kind == "phi":
                if seen_other:
                    raise IRError("block %s: %r must come before every non-phi op" % (b.label, o))
                if len(o.args) != 2:
                    raise IRError("block %s: %r has no latch value - call phi_latch()"
                                  % (b.label, o))
                if b not in targets:
                    raise IRError("block %s carries a phi but nothing branches to it, so there "
                                  "is no second edge for the phi to merge" % b.label)
            else:
                seen_other = True
    if fn.blocks and fn.blocks[-1].term.kind != "ret":
        raise IRError("the last block must end in ret")
    return True


# --- expansion of IR-level operations into selectable ones ---------------------------------------
import math as _math, struct as _struct

def _fbits(x): return _struct.unpack("<I", _struct.pack("<f", x))[0]

# Abramowitz & Stegun 7.1.26: erf(x) = 1 - (a1 t + a2 t^2 + a3 t^3 + a4 t^4 + a5 t^5) e^{-x^2},
# t = 1/(1 + p x), x >= 0, |error| <= 1.5e-7 in exact arithmetic. Odd extension for x < 0.
ERF_P = 0.3275911
ERF_A = (0.254829592, -0.284496736, 1.421413741, -1.453152027, 1.061405429)

def _expand_erf(op):
    """The ops that replace `dest = erf x`, in order, the last one defining `dest`.

    EVERY OP IS ONE THE BACKEND HAS EXECUTED WITH THIS OPERAND SHAPE: fmul, fadd, fmax, fmin,
    recip and exp2 accept kept or single-use operands and constants; `fma` is deliberately NOT
    used, because every executed fma consumed a load (its wait bit set) and the instruction
    checker refuses an fma over ALU results as an unmeasured modifier. The polynomial is Horner
    with fmul+fadd. The sign is restored by a clamp (fmax/fmin of x scaled by 1e30 to [-1, 1])
    rather than a compare, so no predication is needed; at x = 0 the clamp gives 0 and so does
    erf. |x| is fmax(x, -x). e^{-x^2} is exp2(-x^2 log2 e); for |x| > ~9.3 it underflows to 0
    and erf is exactly +-1, which is the correct tail."""
    (x,) = op.args; dest = op.dest; out = []
    def new(kind, args, name):
        v = Value(F32, name); out.append(Op(kind, v, args)); return v
    def c(val, name): return new("const", [Imm(_fbits(val))], name)
    neg = new("fmul", [x, c(-1.0, "erf_m1")], "erf_negx")
    a = new("fmax", [x, neg], "erf_abs")
    t = new("recip", [new("fadd", [new("fmul", [a, c(ERF_P, "erf_p")], "erf_pa"), c(1.0, "erf_one")], "erf_1pa")], "erf_t")
    poly = c(ERF_A[4], "erf_a5")
    for k, coef in ((3, ERF_A[3]), (2, ERF_A[2]), (1, ERF_A[1]), (0, ERF_A[0])):
        poly = new("fadd", [new("fmul", [poly, t], "erf_h%d" % k), c(coef, "erf_a%d" % (k + 1))], "erf_p%d" % k)
    poly = new("fmul", [poly, t], "erf_poly")
    e = new("exp2", [new("fmul", [new("fmul", [a, a], "erf_a2"), c(-1.0 / _math.log(2.0), "erf_nlog2e")], "erf_arg")], "erf_e")
    y = new("fadd", [new("fmul", [new("fmul", [poly, c(-1.0, "erf_m1b")], "erf_npoly"), e], "erf_pe"), c(1.0, "erf_oneb")], "erf_abs_val")
    s = new("fmax", [new("fmin", [new("fmul", [x, c(1e30, "erf_big")], "erf_xs"), c(1.0, "erf_onec")], "erf_smin"), c(-1.0, "erf_m1c")], "erf_sign")
    out.append(Op("fmul", dest, [y, s]))
    return out


def expand(fn):
    """Replace every EXPANDED op in `fn` with selectable ops, in place. Idempotent."""
    for b in fn.blocks:
        ops = []
        for o in b.ops:
            if o.kind == "erf":
                ops.extend(_expand_erf(o))
            else:
                ops.append(o)
        b.ops = ops
    return fn


# --- the explicit requantization primitive (production row P6, machine model 25.130) ---------------
# ONE POLICY OBJECT names every choice a quantized tensor chain makes at an int32 -> 8-bit boundary,
# and every choice this compiler does not implement is refused BY NAME (REQUANT_REFUSALS), never
# inferred or defaulted. The arithmetic, per element, is exactly
#     b = acc + bias[col]                    int32, wrapping (the GEMM's own wrapping add)
#     f = float32(b)                         round to nearest even
#     y = float32(f * scale)                 round to nearest even (a subnormal y is flushed; rint gives 0)
#     r = rint(y)                            round half to even: the retained scalar class's rounding,
#                                            MM 0.11's "int32 -> float scale -> RNE -> int -> clamp"
#     q = clamp(r + zero_point, lo, hi)      [lo, hi] = [-128, 127] (int8) or [0, 255] (uint8)
# The zero point is added AFTER scaling and rounding, and the clamp saturates (never wraps).
# RequantPolicy.reference is the host model; tlower's ('requant', ...) epilogue is the lowering.
REQUANT_ROUNDING = "round_half_to_even"
REQUANT_REFUSALS = {
    "output_type": "refused: requantization output %r: int8 and uint8 are implemented (int4, int16 and "
                   "fp8 outputs are other primitives or unbuilt)",
    "accumulator": "refused: requantization input %r: the int32 accumulator of an int8 GEMM is implemented "
                   "(an fp32 accumulator's quantize-out is the fp8 epilogue, P5)",
    "rounding": "refused: requantization rounding %r: round_half_to_even is implemented (the retained "
                "scalar class's rint); half-away-from-zero, truncation, floor and stochastic are not",
    "zero_point_per_channel": "refused: a per-channel zero point is not implemented (the zero point is one "
                              "compile-time integer per tensor)",
    "zero_point_runtime": "refused: a runtime (buffer) zero point is not implemented (the zero point is a "
                          "compile-time integer)",
    "zero_point_range": "refused: zero point %r is outside the output range of %s",
    "bias_per_tensor": "refused: a per-tensor bias is not implemented (bias is an int32 vector, one per "
                       "output column; a uniform bias is that vector with equal entries)",
    "bias_dtype": "refused: bias dtype %r: an int32 bias added before scaling is implemented (an fp32 "
                  "bias after scaling is not)",
    "scale_per_channel_constant": "refused: a compile-time per-channel scale is not implemented (per-channel "
                                  "scales are an fp32 buffer vector)",
    "scale_value": "refused: requantization scale %r: a positive, finite, normal fp32 is implemented",
    "scale_dtype": "refused: scale dtype %r: fp32 scales are implemented",
    "operand_type": "refused: requantization after a %s x %s GEMM: int8 x int8 is implemented",
    "granularity": "refused: a per-%s requantization vector is not implemented (per tensor and per output "
                   "channel are; block, group and row granularities, the alternative block rules, are not)",
    "gemm_modifier": "refused: requantization with %s is not implemented (whole-tile int8 GEMM, with or "
                     "without the K loop and row, simdgroup and column grids; no accumulate, saturation, K "
                     "split, transpose or other epilogue step)",
}


class RequantRefused(IRError):
    """A requantization class this compiler does not implement, refused by name."""
    def __init__(self, name, *args):
        self.name = name
        super().__init__(REQUANT_REFUSALS[name] % args if args else REQUANT_REFUSALS[name])


class RequantVector:
    """A runtime operand of the requantization: `per` "tensor" (one word) or "channel" (one word per
    output column), `dtype` "float32" (scale) or "int32" (bias), at `offset` bytes into `buffer`."""
    def __init__(self, buffer, offset=0, per="channel", dtype="float32"):
        if not isinstance(buffer, Buffer):
            raise IRError("a requantization vector lives in a declared buffer")
        if per in ("block", "group", "row"):
            raise RequantRefused("granularity", per)
        if per not in ("tensor", "channel"):
            raise IRError("a requantization vector is per 'tensor' or per 'channel', not %r" % (per,))
        if type(offset) is not int or offset < 0 or offset % 4:
            raise IRError("a requantization vector's byte offset is a non-negative multiple of 4")
        self.buffer, self.offset, self.per, self.dtype = buffer, offset, per, dtype

    def __repr__(self):
        return "RequantVector(%s+%d, %s, %s)" % (self.buffer.name, self.offset, self.per, self.dtype)


class RequantPolicy:
    """The producer/consumer policy of one int32 -> int8/uint8 boundary.

    out         "int8" or "uint8" (the consumer's signedness)
    scale       a positive normal fp32 constant (per tensor, compile time), or a RequantVector of
                float32 per "tensor" or per "channel" (runtime)
    bias        None, or a RequantVector of int32 per "channel", added to the accumulator BEFORE scaling
    zero_point  a compile-time int in the output range, added AFTER scaling and rounding (0 = none)
    rounding    "round_half_to_even" only
    accumulator "int32" only
    Anything else raises RequantRefused naming the class."""
    def __init__(self, out="int8", scale=None, bias=None, zero_point=0,
                 rounding=REQUANT_ROUNDING, accumulator="int32"):
        if out not in ("int8", "uint8"):
            raise RequantRefused("output_type", out)
        if accumulator != "int32":
            raise RequantRefused("accumulator", accumulator)
        if rounding != REQUANT_ROUNDING:
            raise RequantRefused("rounding", rounding)
        if isinstance(zero_point, RequantVector):
            raise RequantRefused("zero_point_per_channel" if zero_point.per == "channel" else "zero_point_runtime")
        if isinstance(zero_point, (list, tuple)):
            raise RequantRefused("zero_point_per_channel")
        if type(zero_point) is not int:
            raise IRError("requantization zero_point is a compile-time int")
        lo, hi = (-128, 127) if out == "int8" else (0, 255)
        if not lo <= zero_point <= hi:
            raise RequantRefused("zero_point_range", zero_point, out)
        if isinstance(scale, (list, tuple)):
            raise RequantRefused("scale_per_channel_constant")
        if isinstance(scale, RequantVector):
            if scale.dtype != "float32":
                raise RequantRefused("scale_dtype", scale.dtype)
        else:
            if not isinstance(scale, (int, float)) or isinstance(scale, bool):
                raise RequantRefused("scale_value", scale)
            s32 = _struct.unpack("<f", _struct.pack("<f", float(scale)))[0] if _math.isfinite(float(scale)) else float(scale)
            if not (_math.isfinite(s32) and s32 > 0.0 and s32 >= 2.0 ** -126 and float(scale) == s32):
                raise RequantRefused("scale_value", scale)
        if bias is not None:
            if not isinstance(bias, RequantVector):
                raise RequantRefused("bias_per_tensor")
            if bias.per != "channel":
                raise RequantRefused("bias_per_tensor")
            if bias.dtype != "int32":
                raise RequantRefused("bias_dtype", bias.dtype)
        self.out, self.scale, self.bias, self.zero_point = out, scale, bias, zero_point
        self.rounding, self.accumulator = rounding, accumulator
        self.lo, self.hi = lo, hi

    @property
    def signed(self):
        return self.out == "int8"

    @property
    def scale_class(self):
        if isinstance(self.scale, RequantVector):
            return "tensor-buffer" if self.scale.per == "tensor" else "channel-buffer"
        return "tensor-constant"

    @property
    def class_name(self):
        """The admitted class this policy belongs to, e.g. int8/bias/zp/channel-buffer."""
        return "%s/%s/%s/%s" % (self.out, "bias" if self.bias is not None else "nobias",
                                "zp" if self.zero_point else "nozp", self.scale_class)

    def tlower_step(self, rank_of):
        """tlower's ('requant', signed, zero_point, scale, bias) step; rank_of(buffer) is the binding rank."""
        if isinstance(self.scale, RequantVector):
            scale = (self.scale.per, rank_of(self.scale.buffer), self.scale.offset)
        else:
            scale = ("const", _fbits(float(self.scale)))
        bias = None if self.bias is None else ("channel", rank_of(self.bias.buffer), self.bias.offset)
        return ("requant", self.signed, self.zero_point, scale, bias)

    def reference(self, acc, col, bias_values=None, scale_values=None):
        """The exact host model of one element (pure Python; an independent numpy model lives in
        tools/g17tensorrequant.py). acc: the int32 accumulator; col: its output column."""
        f32 = lambda x: _struct.unpack("<f", _struct.pack("<f", x))[0]
        b = int(acc)
        if self.bias is not None:
            b += int(bias_values[col])
        b = (b + 2 ** 31) % 2 ** 32 - 2 ** 31
        if isinstance(self.scale, RequantVector):
            s = f32(float(scale_values[0 if self.scale.per == "tensor" else col]))
        else:
            s = f32(float(self.scale))
        y = f32(f32(float(b)) * s)       # the double product of two fp32 values is exact
        if abs(y) < 2.0 ** -126:
            y = 0.0
        r = round(y)                     # Python rounds half to even
        return max(self.lo, min(self.hi, r + self.zero_point))

    def __repr__(self):
        return "RequantPolicy(%s, scale=%r, bias=%r, zero_point=%d)" % (self.out, self.scale, self.bias, self.zero_point)


def _tensor_matmul_requant(self, A, B, C, M, N, K, policy, **kw):
    """C = requantize(A @ B) in ONE dispatch: an int8 x int8 GEMM whose int32 D is requantized by
    `policy` (a RequantPolicy) in registers and stored as M x N bytes of int8/uint8 at C (row-major,
    N bytes per row). The explicit IR primitive of production row P6."""
    if not isinstance(policy, RequantPolicy):
        raise IRError("tensor_matmul_requant takes a RequantPolicy")
    a_dtype, b_dtype = kw.pop("a_dtype", "int8"), kw.pop("b_dtype", "int8")
    if (a_dtype, b_dtype) != ("int8", "int8"):
        raise RequantRefused("operand_type", a_dtype, b_dtype)
    # the K loop, the row grid (threadgroups), simdgroups and the column grid (grid_n) compose (MM 25.165);
    # split_k does not: a requantized partial is not a partial of the requantized result
    bad = [k for k in ("accumulate", "saturate", "transA", "transB", "split_fp32", "epilogue",
                       "reduce", "a_converted_from", "b_converted_from", "a_staged") if kw.get(k)]
    bad += [k for k in ("split_k",) if int(kw.get(k, 1)) != 1]
    if bad:
        raise RequantRefused("gemm_modifier", ", ".join(bad))
    return self.tensor_matmul(A, B, C, M, N, K, a_dtype="int8", b_dtype="int8",
                              epilogue=(("requant", policy),), **kw)


