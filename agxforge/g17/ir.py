    def cmp(self, a, imm, pred="lt", name=None, *, source_modifier=0, cap=None):
        """The branch predicate `a PRED imm`. `imm` may be a VALUE - a runtime bound, `i < n` - and
        then a loop latch on it must state `cap`, the most it promises n can be: the backend
        compiles `a < n && a < cap`, so the trip count is bounded by a constant it can prove and
        a broken promise truncates the loop rather than hanging the GPU."""
        if type(source_modifier) is not int or source_modifier not in (0,32):
            raise ValueError('compare source modifier must be 0 or 32')
        if isinstance(imm, Value):
            if source_modifier:
                raise ValueError('a runtime-bound compare takes no source modifier')
            return self._def("cmp", [a, imm], I32, name, pred=pred, cap=cap)
        return self._def("cmp", [a, Imm(imm)], I32, name, pred=pred, source_modifier=source_modifier)
    def phi(self, entry, type=None, name=None):
        """A loop-carried value, seeded by `entry` on the way in.

        The latch value does not exist yet when the header is built, so it is attached afterwards
        with phi_latch(). Until it is, the phi is a value that simply equals its entry value, and
        verify() rejects a function whose phi never got one."""
        t = type or (entry.type if isinstance(entry, Value) else I32)
        return self._def("phi", [entry], t, name)
    @staticmethod
    def phi_latch(phi, value):
        """Close the loop: `value` is what the phi holds on the next iteration."""
        if phi.op.kind != "phi": raise IRError("phi_latch on %r, which is not a phi" % phi)
        if len(phi.op.args) > 1: raise IRError("%r already has a latch value" % phi)
        phi.op.args.append(value)
        return phi
    def icmp(self, a, b, rel="eq", name=None):
        """a REL b as a VALUE, 0 or 1 - not the exec-mask predicate `cmp` produces.

        The backend's only comparison until now set the exec mask, which gates a block; this one
        yields a number, which is what a select, a boolean sum or a saturating count needs. op11372,
        with the relation in its condition-code operand: measured, not assumed - the codes were read
        off execution by running the same instruction on 10 vs 20, 20 vs 10 and 10 vs 10, which
        leaves exactly one relation consistent with all three.
        """
        return self._def("icmp", [a, b], I32, name, rel=rel)

