    def and16(self, v, half, mask, maskreg=None, name=None, pool=False, direct=False):
        """(16-bit half `half` ("L" or "H") of v) & mask, zero-extended to 32 bits, in ONE instruction that
        KEEPS its sources: op426 (8-bit immediate mask) or op428 (the mask in the low half of `maskreg`),
        Apple's own field extraction in quantized kernels (MM 25.138). The four-byte bitwise (op424)
        releases both sources, so extracting several fields from one word cost two copies per field.

        pool=True: op428 with the mask in the program's CONSTANT POOL, Apple's own form (MM 25.141.16). op428's
        second operand is a 16-bit UNIFORM register, not a GPR (the template's type byte is the uniform one,
        which is why a GPR number written there read zero): the driver preloads the pool after the binding
        pointers, so pool halfword h is uniform half 4 x (buffers) + h. Measured in the three-binding
        cooperative class only (tgctl3-u64b loop controls with 1-3 masks): an 8-byte pool vector whose
        halfword 0 is zero and whose masks follow at 1, 2, 3, in a section otherwise byte-identical to the
        empty-pool one. So at most three distinct masks, assigned in first-use order.

        direct=True: read a vector-load lane straight off the load when an earlier consumer of that load has
        already waited (cc's first-consumer rule), instead of cc's waited copy (MM 25.144.4). The first consumer
        still gets the copy: op426/op428's own wait field is unmeasured."""
        extra = dict(direct=True) if direct else {}
        if half not in ("L", "H"):
            raise IRError("and16 reads the L or H half of a register")
        if mask > 0xFFFF or mask < 0:
            raise IRError("and16's mask is a 16-bit value")
        if pool:
            if mask <= 0xFF:
                raise IRError("and16(pool=True) is for masks above 8 bits; an 8-bit mask is op426's immediate")
            masks = self.fn.__dict__.setdefault("pool16", [])
            if mask not in masks:
                if len(masks) >= 3:
                    raise IRError("and16(pool=True): the measured pool-carrying layout holds three masks (an "
                                  "8-byte vector with halfword 0 zero); a fourth selects a different, unwitnessed "
                                  "section layout")
                masks.append(mask)
            h = 1 + masks.index(mask)
            return self._def("and16", [v], I32, name, half=half, mask=mask, pool_h=h,
                             uniform=4 * len(self.fn.buffers) + h, **extra)
        if mask > 0xFF and maskreg is None:
            raise IRError("and16 with a mask above 8 bits takes it in the low half of maskreg")
        args = [v] if mask <= 0xFF else [v, maskreg]
        return self._def("and16", args, I32, name, half=half, mask=mask, **extra)

    def f32_to_f16_rte(self, x, name=None):
        """Narrow an FP32 value to half. op1016 cvt.f32.f16, a real instruction in this direction.

        Its destination is the 16-bit file based at 425 and its source the 32-bit one based at 105,
        which is the mirror of f16_to_f32. Apple compiles `(half)(<a float expression>)` to exactly
        this. The rounding mode is not a field this side writes - the opcode is the one Apple emits
        for a C-level (half) cast, and nothing here has measured an alternative, so "rte" names
        what the instruction does rather than something this compiler selects.
        """
        if getattr(x, "type", None) != I32:
            raise IRError("f32_to_f16_rte takes a 32-bit value; got %r" % getattr(x, "type", None))
        return self._def("f32_to_f16_rte", [x], I16, name)

    @staticmethod
    def _fma16_sources(args, halves):
        halves = tuple(halves) if halves is not None else ("lo",) * 3
        if len(args) != 3 or len(halves) != 3:
            raise IRError("fma16 takes three sources and one half per source")
        for x, h in zip(args, halves):
            t = getattr(x, "type", None)
            if not isinstance(x, Value) or t not in (I16, I32):
                raise IRError("fma16 takes register values (I16, or a half of an I32); got %r" % (x,))
            if h not in ("lo", "hi") or (t == I16 and h != "lo"):
                raise IRError("fma16 source half %r of a %s value: an I16 value is the low half of its register, an "
                              "I32 value is read as its 'lo' or 'hi' half" % (h, t))
        return halves

    def fma16(self, a, b, c, halves=None, name=None):
        """a*b + c in BINARY16 with ONE rounding: op798 ffma.f16 (MM 25.196), Apple's instruction for
        fma(half, half, half). Measured on hardware against Apple's own kernel: 0 of 65,536 random finite
        triples differ from binary16(a*b + c) computed exactly, while 9,890 differ from a rounded multiply
        then a rounded add - so it is fused, not the pair. Each source is sixteen bits: an I16 value (the
        low half of its register, the 425-based file) or one half of an I32 value, `halves[i]` "lo" (425+n)
        or "hi" (281+n) - which is how two halves packed by integer code into one word are read without a
        move. The result is an I16 value."""
        halves = self._fma16_sources([a, b, c], halves)
        return self._def("fma16", [a, b, c], I16, name, halves=halves)

    def f16_to_f32(self, x, name=None):
        """Widen a half to FP32. op1004, an fadd.imm of zero with a SIXTEEN-BIT source.

        There is no conversion opcode in this direction and there does not need to be: the widening
        is the ALU reading a 16-bit operand. Apple compiles `(float)h[i]` to exactly this - op1004
        with reg:105 as the destination and reg:425 as the source - and compiles
        `(float)h[i]*(float)h[j] + f[k]` to no conversion at all, folding the widening into the
        FMA's operands. This exists for the cases where the widening stands alone.
        """
        if getattr(x, "type", None) != I16:
            raise IRError("f16_to_f32 takes a 16-bit value; got %r" % getattr(x, "type", None))
        return self._def("f16_to_f32", [x], I32, name)

    def u32_to_f32(self, x, name=None):
        """Convert an unsigned 32-bit integer to FP32. op11179 cvt.i2f, Apple's own instruction.

        Unlike f16_to_f32 this direction IS a conversion instruction: Apple emits op11179 for
        `(float)u[i]`, 2,641 times across 126 corpus programs. Unlike f32_to_f16_rte there is no
        16-bit file involved - both operands are ordinary 32-bit registers - so nothing here can be
        type-checked beyond the width. THE TYPE SYSTEM CANNOT TELL AN INT FROM A FLOAT: I32 is a
        width, so passing an already-float value would be accepted here and would compute nonsense.
        The front end is what guarantees the operand is the integer the source declared.
        """
