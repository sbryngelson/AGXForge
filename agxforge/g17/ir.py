    ("ulong",          8,     8,     1,   8, "unsigned", 28),
    ("uchar",          1,     1,     1,   1, "unsigned",  1),
    ("bfloat",         2,     2,     1,   2, "float",     7),
    ("half2",          4,     4,     2,   2, "float",    16),
    ("bfloat2",        4,     4,     2,   2, "float",     1),
    ("short2",         4,     4,     2,   2, "signed",   14),
    ("uint2",          8,     8,     2,   4, "unsigned", 16),
    ("float2",         8,     8,     2,   4, "float",    15),
    ("half4",          8,     8,     4,   2, "float",    14),
    ("bfloat4",        8,     8,     4,   2, "float",     1),
    ("uint4",         16,    16,     4,   4, "unsigned", 15),
    ("int4",          16,    16,     4,   4, "signed",   14),
    ("float4",        16,    16,     4,   4, "float",    14),
    # THE ATOMIC DECLARATIONS. `metal::_atomic` is a STRUCT and its field is what gives the width,
    # so the spelling carries the field type rather than collapsing to it: an `atomic_uint` is not
    # a `uint`, because an ordinary load or store of one is not something this backend does. Both
    # are declaration-only for ORDINARY access and absent from ACCESSIBLE_ELEMS, exactly like the
    # wide and vector rows above; what an atomic OPERATION may reach is named in ATOMIC_ELEMS
    # below, which this table cannot imply. Counts are the frozen 197-tag population: 16
    # `metal::_atomic` declarations across 13 sources, whose struct fields are i32 fourteen times
