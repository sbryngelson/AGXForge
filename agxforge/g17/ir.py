    def faddi(self, x, c, ty="f32", sat=False, name=None):
        """x + c, with c carried by the instruction rather than by a register.

        The constant must be one of the 256 the eight-bit float immediate can spell exactly
        (g17asm.float_imm); anything else is refused rather than rounded. ty="f16" reads and writes
        the LOW half of its registers, which is where this IR's 32-bit values keep a half float.
        sat=True clamps the result to [0,1] - the clamp is carried by the opcode, and is measured
        only for f16, so a saturating f32 add is refused rather than guessed at.
        """
        return self._def("faddi", [x], I32, name, imm=float(c), ty=ty, sat=bool(sat))

    def machine(self, opcode, *srcs, **kw):
        """One named machine instruction, its registers allocated and its bits authored from the
        recovered field map rather than from a hand-written encoder.

        This is the escape hatch that makes the ISA's whole authorable set reachable: any opcode
        the field map certifies can be placed in a real program, given registers by the allocator
        and executed, without anyone writing a form for it first. `imms` supplies values for the
        instruction's non-register operands, each in its own domain; anything not named keeps the
        witness's bits, so a program built this way says what it inherited.
        """
        if kw.pop("void", False):
            # An instruction with NO IR RESULT. A comparison that writes a FLAGR does not produce a
            # value the register allocator can hold - the flag is its own file - so the destination
            # is written as a fixed operand and the instruction defines nothing.
            # THE ENCODER TRAVELS WITH THE VOID FORM TOO. It did not, and the first caller that
            # needed one - an instruction with no destination whose operands are not positional -
            # was refused for operands it had in fact supplied.
            self.b.add(Op("machine", None, list(srcs), opcode=opcode,
                          imms=kw.pop("imms", None) or {}, template=kw.pop("template", None),
                          encoder=kw.pop("encoder", None)))
            return None
        # is_load=True says this instruction's result arrives LATE, the way a memory load's does.
        # The store form has a wait bit for exactly that and the backend sets it by looking for an
        # ir `load` - so a load authored through the generic form has to say so, or its consumer
        # reads the register before the value lands. That is what a threadgroup load did: the round
        # trip returned zero until the wait was set. ledger/g17-load-use-hazard.toml
        return self._def("machine", list(srcs), kw.pop("type", I32), kw.pop("name", None),
                         opcode=opcode, imms=kw.pop("imms", None) or {},
                         template=kw.pop("template", None), encoder=kw.pop("encoder", None),
                         is_load=kw.pop("is_load", False))

    def shiftadd(self, a, scale, b, name=None): return self._def("shiftadd", [a, b], I32, name, scale=scale)
