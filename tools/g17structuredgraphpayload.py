#!/usr/bin/env python3
"""Construct measured first-graph physical allocations from explicit fields.

Control words and instruction words retain measured encodings; they are not
a general packet encoder. Base allocations 0, 1 and 2 are outside this module.
"""
import struct

import g17structuredrequests


WORDS = {
    22:{0x28:0x68000,0x2c:0x68000,0x30:0x60000000,0x38:0x68000,
        0xa8:1,0xac:1,0xb0:1,0xb4:64,0xb8:1,0xbc:1},
    23:{0x0:0x2a02c,0x4:0x700c0e,0x8:0x2803c,0xc:4,
        0x10:0x42a08c,0x14:0xc0000,0x18:0x42809c,0x1c:4,
        0x20:0x43046f,0x24:0x42000ca8,0x28:0x43042f,0x2c:0x40000ce8,
        0x30:0x43308f,0x34:0x40000ca8,0x38:0xc000007,0x40:0xe4006c7,
        0x48:0x70100,0x4c:0xd00,0x54:0x2801c,0x5c:0x18134,
        0x60:0x2a00020,0x64:0x2800c,0x68:8,0x6c:0x1a040427,
        0x70:0x2a30021,0x74:0x8088,0x78:0x2801c,0x7c:4,
        0x80:0x40427,0x84:0x12a40030,0x88:0x44092c4b,0x8c:0x4092e5b,
        0x90:0x409240b,0x94:0x409261b,0x98:0x409282b,0x9c:0x4092a3b,
        0xa0:0x409306b,0xa4:0x409327b,0xa8:0xe},
    25:{0x0:0x80000,0x4:0x1000000,0x8:0x2400,0xc:0x40000001,
        0x10:64,0x14:1,0x18:1,0x1c:64,0x20:1,0x24:1,
        0x28:0x60000160,0x2c:0x40000000},
}
INDICES=(20,22,23,24,25,26,27,28)


def allocation(index):
    if index not in INDICES:
        raise ValueError('only measured graph allocations and its empty code backing are supported')
    row=next(r for r in g17structuredrequests.rows() if r[0]==index)
    raw=bytearray(row[6])
    for offset,value in WORDS.get(index,{}).items():
        struct.pack_into('<I',raw,offset,value)
    if index==22:
        for offset,address in ((0x50,0x10000032600),(0x58,0x10000032500)):
            struct.pack_into('<Q',raw,offset,address)
    if index==28:
        for slot in range(3):
            struct.pack_into('<Q',raw,0x1ba0+slot*8,0x10000030000+slot*0x400)
    return bytes(raw)
